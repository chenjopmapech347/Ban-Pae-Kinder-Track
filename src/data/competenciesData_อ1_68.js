/**
 * คำนวณคะแนนเฉลี่ย
 * @param {Object} scores  - { '1.1': 3, '1.2': 2, ... }
 * @param {number|null} domainId - null = ทุก domain
 */
export function calcAvgScoreC68_อ1(scores, domainId = null) {
  const items = domainId
    ? COMPETENCIES_C68_อ1.filter((c) => c.domainId === domainId)
    : COMPETENCIES_C68_อ1;
  const vals = items.map((c) => scores?.[c.code]).filter((v) => v > 0);
  return vals.length ? vals.reduce((a, b) => a + b, 0) / vals.length : 0;
}
