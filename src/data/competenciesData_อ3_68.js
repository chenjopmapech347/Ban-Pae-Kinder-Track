// ─── helpers ──────────────────────────────────────────────────────────────────
export function getCompetenciesByDomain(domainId) {
  return COMPETENCIES_C68.filter(c => c.domainId === domainId);
}

export function calcAvgScoreC68(scores, domainId) {
  const items = domainId
    ? COMPETENCIES_C68.filter(c => c.domainId === domainId)
    : COMPETENCIES_C68;
  const filled = items.filter(c => scores?.[c.code] > 0);
  if (!filled.length) return null;
  return filled.reduce((s, c) => s + scores[c.code], 0) / filled.length;
}
