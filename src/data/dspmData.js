/** อายุเป็นเดือน ณ วันที่ประเมิน — จากวันเกิด (ISO) ถ้าไม่มีใช้อายุปี × 12 (ประมาณ) */
export function ageInMonths(student, dateISO) {
  const b = student?.birthDate;
  if (b && dateISO) {
    const birth = new Date(b), at = new Date(dateISO);
    if (!isNaN(birth) && !isNaN(at)) {
      let m = (at.getFullYear() - birth.getFullYear()) * 12 + (at.getMonth() - birth.getMonth());
      if (at.getDate() < birth.getDate()) m -= 1;
      return { months: Math.max(0, m), estimated: false };
    }
  }
  const y = Number(student?.age);
  if (Number.isFinite(y) && y > 0) return { months: Math.round(y * 12), estimated: true };
  return { months: null, estimated: true };
}

export function ageText(months) {
  if (months == null) return '—';
  const y = Math.floor(months / 12), m = months % 12;
  return `${y} ปี ${m} เดือน`;
}

/** ช่วงอายุที่ตรงกับเด็ก (ต่ำกว่า 31 → ช่วงแรก, เกิน 78 → ช่วงสุดท้าย) */
export function bandForMonths(months) {
  if (months == null) return null;
  const hit = DSPM_BANDS.find(b => months >= b.minM && months <= b.maxM);
  if (hit) return hit;
  return months < DSPM_BANDS[0].minM ? DSPM_BANDS[0] : DSPM_BANDS[DSPM_BANDS.length - 1];
}

/** สรุปผลของ 1 ช่วงอายุ: rec = { GM:'pass'|'fail', ... } */
export function summarizeBand(rec) {
  const vals = DSPM_DOMAINS.map(d => rec?.[d.key] ?? '');
  const done = vals.filter(Boolean).length;
  const failed = DSPM_DOMAINS.filter(d => rec?.[d.key] === 'fail').map(d => d.key);
  if (done === 0) return { status: 'none', done, failed };
  if (failed.length) return { status: 'follow', done, failed };       // มีด้านที่ไม่ผ่าน
  if (done < DSPM_DOMAINS.length) return { status: 'partial', done, failed };
  return { status: 'pass', done, failed };
}
