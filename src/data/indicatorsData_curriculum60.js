// helper: คำนวณ avg ของทุก indicators สำหรับนักเรียน 1 คน
export function calcAvgScore(scores = {}) {
  const vals = Object.values(scores).filter(v => v > 0);
  if (!vals.length) return 0;
  return vals.reduce((s, v) => s + v, 0) / vals.length;
}
